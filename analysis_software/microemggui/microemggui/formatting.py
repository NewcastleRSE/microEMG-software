# FORMATTING CLASSES


# Style settings to pass to GUI
class StyleSettings:
    def __init__(self, h_major=50, h_minor=20, w1=50, w2=75, w3=100):
        # specify widget heights
        self.h_major = h_major
        self.h_minor = h_minor

        # specify widget widths
        self.w1 = 50
        self.w2 = 75
        self.w3 = 100
